import matplotlib.pyplot as plt
import numpy as np


def plot_error_rates(datasets):
    # 使用matplotlib内置的tab10调色板
    colors = plt.cm.tab10.colors

    plt.figure(figsize=(9, 6))

    # 设置字体大小，确保图表适合论文展示
    plt.rcParams.update({'font.size': 12})

    # 为不同的曲线设置不同的样式和颜色
    line_styles = ['-', '--', ':', '-']
    markers = ['o', 's', '^', 'D', 'x']

    index = 0
    for label, info in datasets.items():
        SNRs, BERs, FERs = info['SNRs'], info['BERs'], info['FERs']
        color = colors[index % len(colors)]  # 循环使用颜色
        line_style = line_styles[index % len(line_styles)]  # 循环使用线条样式
        marker = markers[index % len(markers)]  # 循环使用标记
        index += 1

        # 使用统一的颜色，分别使用不同的线条样式区分BER和FER
        # 绘制BER曲线
        if index == 3:
            plt.semilogy(SNRs, BERs, color=color, linestyle=line_style, marker=marker, label=f'BER_{label}', markersize=4)
            # 绘制FER曲线，使用虚线
            plt.semilogy(SNRs, FERs, color=color, linestyle=':', marker=marker, label=f'FER_{label}', markersize=4)
        else:
            plt.semilogy(SNRs, BERs, color=color, linestyle=line_style, marker=marker, label=f'BER_{label}', markersize=4)
            # 绘制FER曲线，使用虚线
            plt.semilogy(SNRs, FERs, color=color, linestyle=':', marker=marker, label=f'FER_{label}', markersize=4)

    # 设置y轴范围
    plt.ylim(1e-7, 1e0)

    # 设置标题和标签
    plt.xlabel('SNR (dB)', fontsize=14)
    plt.ylabel('Error Rate', fontsize=14)
    plt.title('Error Rate vs. SNR', fontsize=16)

    # 添加图例
    plt.legend(loc='best', fontsize=12)

    # 开启网格，增强可读性
    plt.grid(True, which='both', linestyle=':', linewidth=0.5)

    # 显示图表
    plt.tight_layout()  # 自动调整布局
    plt.savefig('./fig/BER_epochs-sft.svg', format='svg')

    plt.show()


